"""Request/response and plan schemas for the personalised plan feature."""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

Goal = Literal["lose_fat", "build_muscle", "endurance", "general_fitness", "mobility"]
Level = Literal["beginner", "intermediate", "advanced"]
Sex = Literal["male", "female", "other"]
Equipment = Literal["none", "dumbbells", "bands", "barbell", "gym"]
Diet = Literal["omnivore", "vegetarian", "vegan", "pescatarian"]
Units = Literal["metric", "imperial"]

DISCLAIMER = (
    "This plan is general fitness and nutrition guidance generated by an AI. It is not medical advice and does not "
    "replace a doctor, physiotherapist or registered dietitian. Stop if you feel pain, dizziness or chest tightness, "
    "and check with a health professional before starting if you have any medical condition or injury."
)

REQUIRED_FIELDS = ("goal", "level", "age", "sex", "height", "weight", "days_per_week")
QUESTIONS = {
    "goal": "What is your main goal: lose fat, build muscle, endurance, general fitness or mobility?",
    "level": "How would you describe your training experience: beginner, intermediate or advanced?",
    "age": "How old are you?",
    "sex": "Which sex should the calorie estimate use: male, female or other?",
    "height": "How tall are you?",
    "weight": "What is your current weight?",
    "days_per_week": "How many days per week can you train?",
}


class Profile(BaseModel):
    """User inputs. Every field is optional so partial form/free-text data can be merged, then checked with
    missing_fields(). Height/weight arrive in `units` and are normalised to cm/kg."""

    model_config = ConfigDict(extra="ignore")

    goal: Goal | None = None
    level: Level | None = None
    age: int | None = None
    sex: Sex | None = None
    units: Units = "metric"
    height: float | None = Field(None, gt=0)
    weight: float | None = Field(None, gt=0)
    target_weight: float | None = Field(None, gt=0)
    equipment: list[Equipment] = Field(default_factory=lambda: ["none"])
    days_per_week: int | None = Field(None, ge=1, le=7)
    minutes_per_session: int = Field(45, ge=10, le=120)
    diet: Diet = "omnivore"
    allergies: list[str] = Field(default_factory=list, max_length=20)
    dislikes: list[str] = Field(default_factory=list, max_length=20)
    injuries: list[str] = Field(default_factory=list, max_length=20)
    medical_conditions: list[str] = Field(default_factory=list, max_length=20)
    pregnant: bool = False
    notes: str = Field("", max_length=1500)

    @model_validator(mode="after")
    def _normalise(self):
        if self.age is not None and not 5 <= self.age <= 110:
            raise ValueError("age must be between 5 and 110")
        imperial = self.units == "imperial"
        for name, lo, hi in (("height", 90, 250), ("weight", 25, 350), ("target_weight", 25, 350)):
            v = getattr(self, name)
            if v is None:
                continue
            metric = v * (2.54 if name == "height" else 0.45359237) if imperial else v
            if not lo <= metric <= hi:
                raise ValueError(f"{name} looks wrong ({'cm' if name == 'height' else 'kg'} {lo}-{hi} expected)")
            object.__setattr__(self, name, round(metric, 1))
        object.__setattr__(self, "units", "metric")  # idempotent: values are metric from here on
        for name in ("allergies", "dislikes", "injuries", "medical_conditions"):
            setattr(self, name, [s.strip()[:80] for s in getattr(self, name) if s and s.strip()])
        if not self.equipment:
            self.equipment = ["none"]
        return self

    def missing_fields(self) -> list[str]:
        return [f for f in REQUIRED_FIELDS if getattr(self, f) is None]

    def merged_over(self, base: "Profile") -> "Profile":
        """Fields explicitly set on self win; everything else comes from base."""
        data = base.model_dump()
        for k, v in self.model_dump(exclude_unset=True).items():
            if v is None or v == "":
                continue
            if isinstance(v, list):  # lists accumulate (injuries from both form and free text)
                v = list(dict.fromkeys([*data.get(k, []), *v]))
                if k == "equipment" and len(v) > 1:
                    v = [e for e in v if e != "none"]
            data[k] = v
        return Profile.model_validate(data)


class GenerateRequest(BaseModel):
    profile: Profile | None = None
    free_text: str | None = Field(None, max_length=3000)
    adjustment: str | None = Field(None, max_length=300, description='e.g. "make it easier", "no jumping"')

    @model_validator(mode="after")
    def _something(self):
        if self.profile is None and not (self.free_text and self.free_text.strip()):
            raise ValueError("send a structured profile, free_text, or both")
        return self


# ---- plan body ---------------------------------------------------------------------------------------------


class ExerciseItem(BaseModel):
    exercise_id: str | None = None  # catalogue id → can open /workout/[id] for live form coaching
    name: str = Field(max_length=80)
    sets: int = Field(ge=1, le=8)
    reps: int | None = Field(None, ge=1, le=60)
    duration_sec: int | None = Field(None, ge=5, le=600)
    rest_sec: int = Field(60, ge=0, le=300)
    notes: str = Field("", max_length=300)

    @model_validator(mode="after")
    def _reps_or_time(self):
        if (self.reps is None) == (self.duration_sec is None):
            raise ValueError("give exactly one of reps or duration_sec")
        return self


class DayPlan(BaseModel):
    day: str = Field(max_length=20)
    name: str = Field(max_length=60)
    warmup: list[str] = Field(min_length=1, max_length=8)
    exercises: list[ExerciseItem] = Field(min_length=1, max_length=12)
    cooldown: list[str] = Field(min_length=1, max_length=8)


class WeekPlan(BaseModel):
    week: int
    focus: str
    days: list[DayPlan]


class Meal(BaseModel):
    name: str = Field(max_length=60)
    description: str = Field(max_length=300)
    approx_kcal: int = Field(ge=0, le=2500)


class MealDay(BaseModel):
    name: str = Field(max_length=40)
    meals: list[Meal] = Field(min_length=2, max_length=6)


class Nutrition(BaseModel):
    calories: int
    protein_g: int
    carbs_g: int
    fat_g: int
    water_l: float
    notes: list[str] = []
    meal_days: list[MealDay]


class PlanBody(BaseModel):
    title: str
    summary: str
    disclaimer: str = DISCLAIMER
    safety_flags: list[str] = []
    progression: str
    weeks: list[WeekPlan]
    nutrition: Nutrition
    schema_version: int = 1


class StoredPlan(BaseModel):
    id: str
    user_id: str
    created_at: datetime
    model: str
    profile: Profile
    plan: PlanBody


class PlanSummary(BaseModel):
    id: str
    title: str
    created_at: datetime
    goal: str | None


class SafetyReport(BaseModel):
    blocked: bool = False
    reasons: list[str] = []  # why the request was refused
    flags: list[str] = []  # allowed, but the user should see these


class GenerateResponse(BaseModel):
    status: Literal["ok", "needs_clarification", "blocked"]
    plan: StoredPlan | None = None
    questions: list[str] = []
    profile: Profile | None = None  # what was understood so far, to prefill the form
    safety: SafetyReport = SafetyReport()


# ---- what the LLM is asked to produce (smaller than PlanBody so local models stay reliable) -------------------


class LLMWorkout(BaseModel):
    title: str = Field(max_length=80)
    summary: str = Field(max_length=500)
    week_focus: list[str] = Field(min_length=4, max_length=4)
    days: list[DayPlan]


class LLMMeals(BaseModel):
    notes: list[str] = Field(default_factory=list, max_length=6)
    meal_days: list[MealDay] = Field(min_length=3, max_length=3)
